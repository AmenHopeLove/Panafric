-- 3. News Table (For Dynamic News Updates)
CREATE TABLE IF NOT EXISTS news (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  title TEXT NOT NULL,
  content TEXT NOT NULL,
  excerpt TEXT NOT NULL,
  category TEXT NOT NULL, -- e.g., 'Firm News', 'Legal Alerts', 'Press Release'
  image_url TEXT,
  published_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  author TEXT DEFAULT 'Pan Afric Law Firm'
);

ALTER TABLE news ENABLE ROW LEVEL SECURITY;

-- Allow public read access to News
CREATE POLICY "Public News Access" ON news
  FOR SELECT USING (true);

-- Admins can manage news
CREATE POLICY "Admins manage news" ON news
  FOR ALL USING (
    EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
  );

